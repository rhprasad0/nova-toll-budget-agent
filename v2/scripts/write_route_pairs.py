"""Write agent_tools/route_pairs.py from the committed Oracle route graph.

The deployed agent bundles only agent/, agent_tools/ and the SOP, so the
reachable (origin, destination) point pairs are generated into a module.
Run from v2/: `uv run python scripts/write_route_pairs.py`.
"""

from __future__ import annotations

import sys
from collections import defaultdict, deque
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from oracle.build_oracle_data import build_connections, build_points  # noqa: E402

TARGET = ROOT / "agent_tools" / "route_pairs.py"
HEADER = '''"""Reachable (origin, destination) point pairs of the Oracle route graph.

Generated by scripts/write_route_pairs.py; do not edit by hand.
"""

REACHABLE_PAIRS: frozenset[tuple[str, str]] = frozenset(
    {
'''
FOOTER = """    }
)
"""


def reachable_pairs() -> list[tuple[str, str]]:
    """Same walk as oracle.build_oracle_data.graph_metrics, keeping the pairs."""
    points = build_points()
    adjacency: dict[str, list[str]] = defaultdict(list)
    for connection in build_connections(points).values():
        adjacency[connection.from_point_id].append(connection.to_point_id)
    pairs: list[tuple[str, str]] = []
    for origin in points.values():
        if origin.point_type not in {"entry", "airport"}:
            continue
        queue = deque([origin.point_id])
        visited = {origin.point_id}
        while queue:
            point_id = queue.popleft()
            if point_id != origin.point_id:
                if points[point_id].point_type in {"exit", "airport"}:
                    pairs.append((origin.point_id, point_id))
                if points[point_id].point_type == "airport":
                    continue
            for destination in adjacency[point_id]:
                if destination not in visited:
                    visited.add(destination)
                    queue.append(destination)
    return sorted(pairs)


def render() -> str:
    body = "".join(
        f'        ("{origin}", "{destination}"),\n'
        for origin, destination in reachable_pairs()
    )
    return HEADER + body + FOOTER


if __name__ == "__main__":
    TARGET.write_text(render())
    print(f"wrote {TARGET.relative_to(ROOT)}")
